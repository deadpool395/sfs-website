const TZ = 'Asia/Kolkata';
function fmtDate(d, opts = { day: 'numeric', month: 'short', year: 'numeric' }) {
  if (!d) return '';
  return new Date(d).toLocaleDateString('en-IN', { timeZone: TZ, ...opts });
}
function dateParts(d) {
  const dt = new Date(d);
  return {
    day: dt.toLocaleDateString('en-IN', { timeZone: TZ, day: '2-digit' }),
    month: dt.toLocaleDateString('en-IN', { timeZone: TZ, month: 'short' }),
  };
}
// Value for <input type="datetime-local"> in Indian time.
function toInputDate(d) {
  if (!d) return '';
  const dt = new Date(d);
  const p = Object.fromEntries(
    new Intl.DateTimeFormat('en-GB', { timeZone: TZ, year: 'numeric', month: '2-digit', day: '2-digit', hour: '2-digit', minute: '2-digit', hour12: false })
      .formatToParts(dt)
      .map((x) => [x.type, x.value])
  );
  return `${p.year}-${p.month}-${p.day}T${p.hour === '24' ? '00' : p.hour}:${p.minute}`;
}
const initials = (name) =>
  String(name || '?')
    .replace(/^(dr|mr|mrs|ms|sr|fr|rev)\.?\s+/i, '')
    .split(/\s+/)
    .filter(Boolean)
    .slice(0, 2)
    .map((w) => w[0].toUpperCase())
    .join('');
const escapeHtml = (s) =>
  String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);
// Escapes text, then turns *words* into <em>words</em> for headline accents.
const emph = (s) => escapeHtml(s).replace(/\*([^*]+)\*/g, '<em>$1</em>');
const isExternal =(url) => /^https?:\/\//i.test(url || '');
const mediaUrl = (id, size) => (id ? `/media/${id}${size ? `?size=${size}` : ''}` : null);

